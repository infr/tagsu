const CODE_OF = new Map<string, number>(ROM_CHARS.map((c, code) => [c, code] as [string, number]).filter(([c]) => c));
const ALIASES: Record<string, string> = { "’": "'", "‘": "'", "“": '"', "”": '"', "–": "-", "—": "-", " ": " " };

export function lcdCode(ch: string): number {
  const cp = ch.codePointAt(0) ?? 0;
  if (cp >= 0xff61 && cp <= 0xff9f) return cp - 0xff61 + 0xa1;
  if (cp === 0x3099) return 0xde;
  if (cp === 0x309a) return 0xdf;
  return CODE_OF.get(ch) ?? CODE_OF.get(ALIASES[ch] ?? "") ?? 0x3f;
}

/** Hiragana becomes katakana and voiced kana split into kana + mark, as the ROM stores them. */
export function toLcdText(text: string): string {
  return text.replace(/[ぁ-ヿ]/g, (ch) => {
    const cp = ch.codePointAt(0)!;
    const kata = cp <= 0x3096 ? String.fromCodePoint(cp + 0x60) : ch;
    return kata.normalize("NFD");
  });
}

