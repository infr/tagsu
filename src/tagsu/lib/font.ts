export const GLYPHS: number[][] = ROM_HEX.map((h) => {
  if (!h) return [];
  const v = parseInt(h, 16);
  return Array.from({ length: 8 }, (_, r) => Math.floor(v / 32 ** (7 - r)) % 32);
});

