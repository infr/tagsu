const SPACE = 8;
const paths = new Map<string, Path2D>();

/** `width` fits the text to that many px, by spacing the letters out ("track") or narrowing them ("squeeze"). */
type Options = { align?: "left" | "center"; stroke?: number; width?: number; fit?: "track" | "squeeze" };

/** Draws `s` with its caps `cap` px tall, vertically centred on `y`; `stroke` is the line width relative to `cap`. */
export function strokeText(ctx: CanvasRenderingContext2D, s: string, x: number, y: number, cap: number, { align = "center", stroke = 0.16, width: target, fit = "track" }: Options = {}) {
  const k = cap / 21;
  const glyphs = [...s].map((ch) => GLYPHS[ch === "−" ? "-" : ch]);
  const natural = glyphs.reduce((w, g) => w + (g ? g[1] * 2 : SPACE * 2), 0);
  const kx = target && fit === "squeeze" ? target / (natural * k) : 1;
  const tracking = target && fit === "track" && glyphs.length > 1 ? (target / k - natural) / (glyphs.length - 1) : 0;
  const advance = (g: [string, number] | undefined) => (g ? g[1] * 2 : SPACE * 2) + tracking;
  const width = (natural + tracking * (glyphs.length - 1)) * k * kx;
  ctx.save();
  ctx.translate(align === "center" ? x - width / 2 : x, y - 11.5 * k);
  ctx.scale(k * kx, k);
  ctx.lineWidth = (stroke * cap) / k;
  ctx.lineCap = "round";
  ctx.lineJoin = "round";
  for (const g of glyphs) {
    if (g) {
      let path = paths.get(g[0]);
      if (!path) paths.set(g[0], (path = new Path2D(g[0])));
      ctx.stroke(path);
    }
    ctx.translate(advance(g), 0);
  }
  ctx.restore();
}
